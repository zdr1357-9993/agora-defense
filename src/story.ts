export type Line = [string, string, string?];  // 세 번째: 그 대사 동안 반짝일 화면 요소(선택)

export interface StoryStage {
  id: string;
  chapter: number;
  title: string;
  /** 연도·장소 (화면 위 작은 글씨) */
  when: string;
  /** 길·보스 기술·배경을 빌려 올 본편 스테이지 */
  base: 'S1' | 'S2' | 'S3' | 'S4' | 'S5';
  boss: string;
  intro: Line[];
  outro: Line[];
  /** 깨면 소환 목록에 추가되는 흔함 (실제 이름) */
  unlock?: string[];
  /** 깨면 돌아오는 기억 = 철학자 카드 (실제 이름) */
  memories: string[];
  /** 시작 튜토리얼: 이 판에서 소환되는 흔함과 웨이브 수 */
  pool?: string[];
  waves?: number;
  /** 이야기 끝에 나오는 오늘의 질문과 답 */
  qa?: [string, string];
}

